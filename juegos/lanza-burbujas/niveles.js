export const TOTAL_NIVELES = NIVELES.length;

/** Mundo (0-5) de un nivel (1-30). */
export function mundoDe(nivel) {
  return Math.min(MUNDOS.length - 1, Math.floor((Math.max(1, nivel) - 1) / NIVELES_POR_MUNDO));
}

/** Filas del nivel convertidas a números de color. */
export function filasDe(nivel) {
  const filas = NIVELES[Math.max(1, Math.min(TOTAL_NIVELES, nivel)) - 1];
  return filas.map((f) => [...f].map((ch) => Math.max(0, LETRAS_COLOR.indexOf(ch))));
}
